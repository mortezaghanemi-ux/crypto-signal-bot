"""Backtest for the signal strategy in bot.py (standard library only).

Usage:
    python backtest.py        # last 2 years of BTC/USDT 4h candles
    python backtest.py 3      # last 3 years

Rules used (to avoid fooling ourselves):
- A signal is read on a CLOSED candle; the trade enters at the NEXT candle's open.
- Stop-loss / take-profit are checked on every later candle using high/low.
- If SL and TP are both touched in the same candle, we assume the SL hit first.
- Only one trade at a time. A trade is closed at the market after MAX_HOLD candles.
- Fees: FEE per side (default 0.1%), subtracted from every trade.
Educational tool, not financial advice.
"""

import sys
import time

import bot

MAX_HOLD = 50  # candles (~8 days on 4h)
FEE = 0.001  # 0.1% per side
WARMUP = 300  # candles skipped at the start so EMA200 is settled
CANDLE_MS = 4 * 3600 * 1000


# ---------------- History download ----------------
def history_bybit(start_ms):
    out = {}
    end = int(time.time() * 1000)
    while end > start_ms:
        url = (
            "https://api.bybit.com/v5/market/kline"
            f"?category=spot&symbol=BTCUSDT&interval=240&limit=1000&end={end}"
        )
        rows = bot.http_get_json(url)["result"]["list"]  # newest first
        if not rows:
            break
        for r in rows:
            out[int(r[0])] = (int(r[0]), float(r[1]), float(r[2]), float(r[3]), float(r[4]))
        oldest = int(rows[-1][0])
        if oldest >= end:
            break
        end = oldest - 1
    return sorted(out.values())


def history_kucoin(start_ms):
    out = {}
    end_s = int(time.time())
    start_s = start_ms // 1000
    while end_s > start_s:
        url = (
            "https://api.kucoin.com/api/v1/market/candles"
            f"?type=4hour&symbol=BTC-USDT&startAt={start_s}&endAt={end_s}"
        )
        rows = bot.http_get_json(url)["data"]  # newest first
        if not rows:
            break
        for r in rows:
            t = int(r[0]) * 1000
            out[t] = (t, float(r[1]), float(r[3]), float(r[4]), float(r[2]))
        oldest = int(rows[-1][0])
        if oldest >= end_s:
            break
        end_s = oldest - 1
    return sorted(out.values())


def load_history(years):
    start_ms = int((time.time() - years * 365 * 24 * 3600) * 1000)
    last_error = None
    for name, fn in (("bybit", history_bybit), ("kucoin", history_kucoin)):
        try:
            candles = fn(start_ms)
            if len(candles) < WARMUP + 100:
                raise ValueError(f"only {len(candles)} candles returned")
            print(f"History source: {name} ({len(candles)} candles)")
            return candles
        except Exception as e:  # noqa: BLE001
            last_error = e
            print(f"{name} failed: {e}")
    raise SystemExit(f"Could not download history. Last error: {last_error}")


# ---------------- Backtest engine ----------------
def run_backtest(candles):
    d = bot.compute(candles)
    n = len(candles)
    trades = []
    i = WARMUP
    while i < n - 2:
        sig = bot.signal_at(d, i)
        if not sig:
            i += 1
            continue

        a = d["atr"][i]
        side = sig["side"]
        direction = 1 if side == "BUY" else -1
        entry = candles[i + 1][1]  # next candle's open
        sl = entry - direction * bot.SL_ATR_MULT * a
        tp = entry + direction * bot.TP_ATR_MULT * a
        risk = bot.SL_ATR_MULT * a  # price distance = 1R

        exit_price, reason, j = None, None, i + 1
        last_j = min(n - 1, i + MAX_HOLD)
        while j <= last_j:
            _, _, high, low, close = candles[j]
            hit_sl = low <= sl if direction == 1 else high >= sl
            hit_tp = high >= tp if direction == 1 else low <= tp
            if hit_sl:  # SL first if both are touched
                exit_price, reason = sl, "SL"
                break
            if hit_tp:
                exit_price, reason = tp, "TP"
                break
            j += 1
        if exit_price is None:
            j = last_j
            exit_price, reason = candles[j][4], "TIME"

        gross_r = direction * (exit_price - entry) / risk
        fee_r = (2 * FEE * entry) / risk
        trades.append(
            {
                "time": candles[i][0],
                "side": side,
                "entry": entry,
                "exit": exit_price,
                "reason": reason,
                "r": gross_r - fee_r,
                "bars": j - i,
            }
        )
        i = j + 1  # one trade at a time
    return trades


def summarize(trades, candles):
    if not trades:
        print("No trades were generated by these rules in this period.")
        return

    def stats(ts, label):
        if not ts:
            print(f"{label}: no trades")
            return
        wins = [t["r"] for t in ts if t["r"] > 0]
        losses = [t["r"] for t in ts if t["r"] <= 0]
        total = sum(t["r"] for t in ts)
        pf = (sum(wins) / -sum(losses)) if losses and sum(losses) < 0 else float("inf")
        print(
            f"{label}: {len(ts)} trades | win rate {len(wins) / len(ts) * 100:.0f}% "
            f"| avg {total / len(ts):+.2f}R | total {total:+.1f}R | profit factor {pf:.2f}"
        )

    print("=" * 44)
    first = bot.fmt_time(candles[WARMUP][0])
    last = bot.fmt_time(candles[-1][0])
    print(f"Period: {first[:10]} -> {last[:10]}")
    stats(trades, "ALL ")
    stats([t for t in trades if t["side"] == "BUY"], "BUY ")
    stats([t for t in trades if t["side"] == "SELL"], "SELL")

    reasons = {}
    for t in trades:
        reasons[t["reason"]] = reasons.get(t["reason"], 0) + 1
    print("Exits:", ", ".join(f"{k}={v}" for k, v in sorted(reasons.items())))

    # Year-by-year breakdown: is the result stable or driven by one period?
    print("-" * 44)
    print("Per year (total R):   trades |  ALL  |  BUY  | SELL")
    years = sorted({int(bot.fmt_time(t["time"])[:4]) for t in trades})
    for y in years:
        ys = [t for t in trades if int(bot.fmt_time(t["time"])[:4]) == y]
        tot = sum(t["r"] for t in ys)
        buy = sum(t["r"] for t in ys if t["side"] == "BUY")
        sell = sum(t["r"] for t in ys if t["side"] == "SELL")
        print(f"  {y}:              {len(ys):4d}   | {tot:+5.1f} | {buy:+5.1f} | {sell:+5.1f}")
    print("-" * 44)

    # Max drawdown in R and equity if risking 1% per trade
    cum, peak, max_dd, equity = 0.0, 0.0, 0.0, 1.0
    for t in trades:
        cum += t["r"]
        peak = max(peak, cum)
        max_dd = max(max_dd, peak - cum)
        equity *= 1 + 0.01 * t["r"]
    print(f"Max drawdown: {max_dd:.1f}R")
    print(f"Risking 1% per trade: equity x{equity:.2f}")

    start_price = candles[WARMUP][1]
    end_price = candles[-1][4]
    print(f"Buy & hold over same period: {(end_price / start_price - 1) * 100:+.0f}%")
    print("=" * 44)
    print("Last trades:")
    for t in trades[-5:]:
        print(
            f"  {bot.fmt_time(t['time'])[:16]}  {t['side']:4}  "
            f"{t['entry']:.0f} -> {t['exit']:.0f}  {t['reason']:4} {t['r']:+.2f}R"
        )


if __name__ == "__main__":
    years = float(sys.argv[1]) if len(sys.argv) > 1 else 2.0
    data = load_history(years)
    summarize(run_backtest(data), data)
